std::uint8_t HexNibble(const char ch) {
  if (ch >= '0' && ch <= '9') {
    return static_cast<std::uint8_t>(ch - '0');
  }
  if (ch >= 'a' && ch <= 'f') {
    return static_cast<std::uint8_t>(ch - 'a' + 10);
  }
  return static_cast<std::uint8_t>(ch - 'A' + 10);
}

template <std::size_t ByteCount>
std::array<std::uint8_t, ByteCount> DecodeHexBytes(std::string_view hex) {
  std::array<std::uint8_t, ByteCount> bytes{};
  for (std::size_t i = 0; i < ByteCount; ++i) {
    bytes[i] = static_cast<std::uint8_t>(
        (HexNibble(hex[i * 2]) << 4) | HexNibble(hex[i * 2 + 1]));
  }
  return bytes;
}

