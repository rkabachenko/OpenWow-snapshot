const RetailMatrixTransformTables* GetRetailMatrixTransformTables(
    const std::uint32_t total_columns) {
  switch (total_columns) {
    case kMatrixTransform156TotalColumns:
      return &Retail156Tables();
    case kMatrixTransform176TotalColumns:
      return &Retail176Tables();
    default:
      return nullptr;
  }
}

bool ReadMatrixBit(const MatrixTransformBitMatrix& matrix,
                   const std::uint32_t row,
                   const std::uint32_t column) {
  if (row >= matrix.bit_count || column >= matrix.bit_count) {
    return false;
  }

  const std::uint32_t bit_index = row * matrix.stride + column;
  const auto byte_index = static_cast<std::size_t>(bit_index >> 3);
  if (byte_index >= matrix.data.size()) {
    return false;
  }

  const std::uint8_t byte = matrix.data[byte_index];
  return ((byte >> (bit_index & 7u)) & 1u) != 0;
}

bool CMatrixTransform_BuildSourceBit(MatrixTransform* transform) {
  if (transform == nullptr) {
    return false;
  }

  transform->rows.clear();
  transform->columns.clear();
  transform->source_bits = {};
  transform->check_bits = {};
  transform->inverse_check_bits = {};

  transform->total_columns = transform->input_columns + transform->check_columns;
  const RetailMatrixTransformTables* tables =
      GetRetailMatrixTransformTables(transform->total_columns);
  if (tables == nullptr
      || transform->input_columns != tables->source_bits.bit_count
      || transform->check_columns != tables->check_bits.bit_count
      || transform->row_count > tables->source_bits.bit_count) {
    return false;
  }

  transform->source_bits = tables->source_bits;
  transform->check_bits = tables->check_bits;
  transform->inverse_check_bits = tables->inverse_check_bits;
  transform->rows.assign(transform->row_count, {});
  transform->columns.assign(transform->total_columns, {});

  for (std::uint32_t column_index = 0; column_index < transform->total_columns; ++column_index) {
    transform->columns[column_index].index = static_cast<std::uint16_t>(column_index);
  }

  for (std::uint32_t row_index = 0; row_index < transform->row_count; ++row_index) {
    MatrixTransformRowLinks* row_links = &transform->rows[row_index];

    for (std::uint32_t column_index = 0; column_index < transform->input_columns; ++column_index) {
      if (ReadMatrixBit(transform->source_bits, row_index, column_index)
          && !AddLink(row_links,
                      &transform->columns[column_index],
                      static_cast<std::uint16_t>(column_index),
                      static_cast<std::uint16_t>(row_index))) {
        transform->source_bits = {};
        transform->check_bits = {};
        transform->inverse_check_bits = {};
        transform->rows.clear();
        transform->columns.clear();
        return false;
      }
    }

    for (std::uint32_t check_index = 0; check_index < transform->check_columns; ++check_index) {
      const std::uint32_t column_index = transform->input_columns + check_index;
      if (ReadMatrixBit(transform->check_bits, row_index, check_index)
          && !AddLink(row_links,
                      &transform->columns[column_index],
                      static_cast<std::uint16_t>(column_index),
                      static_cast<std::uint16_t>(row_index))) {
        transform->source_bits = {};
        transform->check_bits = {};
        transform->inverse_check_bits = {};
        transform->rows.clear();
        transform->columns.clear();
        return false;
      }
    }
  }

  return true;
}

