MatrixTransformBitMatrix MakeBorrowedMatrix(std::string_view name,
                                            const std::uint32_t bit_count,
                                            std::span<const std::uint8_t> data) {
  return MatrixTransformBitMatrix{
      .name = name,
      .bit_count = bit_count,
      .stride = bit_count,
      .data = data,
      .borrowed = true,
  };
}

