bool AddLink(MatrixTransformRowLinks* row_links,
             MatrixTransformColumnLinks* column_links,
             const std::uint16_t column_index,
             const std::uint16_t row_index) {
  if (row_links == nullptr || column_links == nullptr) {
    return false;
  }
  if (row_links->input_count >= row_links->input_indices.size()) {
    return false;
  }
  if (column_links->row_count >= column_links->row_indices.size()) {
    return false;
  }

  row_links->input_indices[row_links->input_count++] = column_index;
  column_links->row_indices[column_links->row_count++] = row_index;
  return true;
}

