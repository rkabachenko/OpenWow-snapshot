void THuffmanTree::Init() {

    for (int i = 0; i < kHuffmanNodeCount; ++i) {
        nodes_[i].link_prev = 0;
        nodes_[i].link_next = 0;
    }

    InitializeStormIntrusiveListRoot(sorted_list_, 0);

    InitializeStormIntrusiveListRoot(free_list_, 0);

    version_ = 1;

    next_free_index_ = 0;
}

void THuffmanTree::Clear() {

    UnlinkAllStormIntrusiveNativeNodes(free_list_);

    {
        auto* root_link = GetStormIntrusiveRootLinkWords(free_list_);
        if (root_link->previous_link != 0) {
            UnlinkStormIntrusiveNativeLink<std::uintptr_t>(
                reinterpret_cast<std::uintptr_t>(root_link));
        }
    }

    UnlinkAllStormIntrusiveNativeNodes(sorted_list_);

    {
        auto* root_link = GetStormIntrusiveRootLinkWords(sorted_list_);
        if (root_link->previous_link != 0) {
            UnlinkStormIntrusiveNativeLink<std::uintptr_t>(
                reinterpret_cast<std::uintptr_t>(root_link));
        }
    }

    for (int i = kHuffmanNodeCount - 1; i >= 0; --i) {
        UnlinkNode(&nodes_[i]);
    }
}

void THuffmanTree::UnlinkNode(THuffmanNode* node) {
    if (node->link_prev == 0) {
        return;
    }

    UnlinkStormIntrusiveNativeLink<std::uintptr_t>(
        reinterpret_cast<std::uintptr_t>(&node->link_prev));
}

void THuffmanOutputBuffer::OutputBits(std::uint32_t value,
                                       std::uint32_t bit_count) {
    bit_cache |= value << bits_held;
    bits_held += bit_count;

    while (bits_held >= 8) {
        if (remaining > 0) {
            *write_ptr++ = static_cast<std::uint8_t>(bit_cache);
            --remaining;
        }
        bit_cache >>= 8;
        bits_held -= 8;
    }
}

void THuffmanOutputBuffer::FlushBits() {
    if (bits_held == 0) {
        return;
    }

    do {
        if (remaining > 0) {
            *write_ptr++ = static_cast<std::uint8_t>(bit_cache);
            --remaining;
        }

        const std::uint32_t held = bits_held;
        bit_cache >>= 8;
        const std::uint32_t consumed = (held <= 8) ? held : 8;
        bits_held = held - consumed;
    } while (bits_held != 0);
}

