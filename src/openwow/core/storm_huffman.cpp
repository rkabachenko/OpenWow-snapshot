THuffmanNode* THuffmanTree::AllocNode(int insert_mode) {
    if (next_free_index_ >= kHuffmanNodeCount)
        return nullptr;

    THuffmanNode* node = &nodes_[next_free_index_++];
    node->link_prev = 0;
    node->link_next = 0;
    node->symbol = 0;
    node->weight = 0;
    node->child0 = nullptr;
    node->child1 = nullptr;

    auto* sentinel = GetListSentinel(sorted_list_);
    if (insert_mode == 0) {

        node->link_prev = reinterpret_cast<std::uintptr_t>(sentinel);
        node->link_next = sorted_list_.head_node;

        if (!IsSentinelOrNull(sorted_list_.head_node)) {
            auto* first = reinterpret_cast<THuffmanNode*>(sorted_list_.head_node);
            first->link_prev = reinterpret_cast<std::uintptr_t>(&node->link_prev);
        } else {

            sentinel->previous_link =
                reinterpret_cast<std::uintptr_t>(&node->link_prev);
        }
        sorted_list_.head_node = reinterpret_cast<std::uintptr_t>(node);
    } else {

        node->link_next =
            reinterpret_cast<std::uintptr_t>(sentinel)
            | kStormIntrusiveSentinelBit<std::uintptr_t>;
        node->link_prev = sentinel->previous_link;

        sentinel->previous_link =
            reinterpret_cast<std::uintptr_t>(&node->link_prev);

        if (IsSentinelOrNull(sorted_list_.head_node)) {

            sorted_list_.head_node = reinterpret_cast<std::uintptr_t>(node);
        }
    }

    return node;
}

void THuffmanTree::BuildTree(std::uint8_t compression_type) {

    for (int i = 0; i < kHuffmanSymbolCount; ++i)
        symbol_table_[i] = nullptr;

    for (int i = 0; i < kHuffmanNodeCount; ++i) {
        nodes_[i].link_prev = 0;
        nodes_[i].link_next = 0;
    }
    InitializeStormIntrusiveListRoot(sorted_list_, 0);
    InitializeStormIntrusiveListRoot(free_list_, 0);
    next_free_index_ = 0;
    version_ = 0;

    const int data_type = compression_type & 0x0F;

    const std::uint8_t* dist_table = nullptr;
    if (data_type >= 0 && data_type < 9)
        dist_table = kDataDistributionTable[data_type];

    std::uint32_t max_weight = 0;

    for (int i = 0; i < 256; ++i) {
        if (dist_table != nullptr && dist_table[i] != 0) {
            THuffmanNode* node = AllocNode(0);
            if (node == nullptr)
                return;
            node->symbol = static_cast<std::uint32_t>(i);
            node->weight = dist_table[i];
            symbol_table_[i] = node;
            max_weight = FixupItemPosByWeight(sorted_list_, node, max_weight);
        }
    }

    THuffmanNode* eof_node = AllocNode(1);
    if (eof_node != nullptr) {
        eof_node->symbol = kHuffmanEOFSymbol;
        eof_node->weight = 1;
        symbol_table_[kHuffmanEOFSymbol] = eof_node;
        max_weight = FixupItemPosByWeight(sorted_list_, eof_node, max_weight);
    }

    THuffmanNode* nyt_node = AllocNode(1);
    if (nyt_node != nullptr) {
        nyt_node->symbol = kHuffmanEscapeSymbol;
        nyt_node->weight = 1;
        symbol_table_[kHuffmanEscapeSymbol] = nyt_node;
        max_weight = FixupItemPosByWeight(sorted_list_, nyt_node, max_weight);
    }

    THuffmanNode* pChildLo = GetLastNode(sorted_list_);
    while (pChildLo != nullptr) {
        THuffmanNode* pChildHi = GetPrevNode(pChildLo);
        if (pChildHi == nullptr)
            break;

        THuffmanNode* parent_node = AllocNode(1);
        if (parent_node == nullptr)
            return;
        parent_node->symbol = 0;
        parent_node->weight = pChildLo->weight + pChildHi->weight;
        parent_node->child1 = pChildLo;

        pChildLo->child0 = parent_node;
        pChildHi->child0 = parent_node;

        max_weight = FixupItemPosByWeight(sorted_list_, parent_node, max_weight);

        pChildLo = GetPrevNode(pChildHi);
    }

    version_ = 1;
}

void THuffmanTree::EncodeSymbol(THuffmanOutputBuffer* output, int symbol) {
    if (symbol < 0 || symbol >= kHuffmanSymbolCount)
        return;

    THuffmanNode* pItem = symbol_table_[symbol];
    if (pItem == nullptr)
        return;

    std::uint32_t bit_buffer = 0;
    std::uint32_t bit_count = 0;

    THuffmanNode* pParent = pItem->child0;
    while (pParent != nullptr) {

        if (pParent->child1 != pItem) {

            bit_buffer = (bit_buffer << 1) | 1;
        } else {

            bit_buffer = (bit_buffer << 1) | 0;
        }
        bit_count++;
        pItem = pParent;
        pParent = pItem->child0;
    }

    output->OutputBits(bit_buffer, bit_count);
}

int THuffmanTree::DecodeSymbol(THuffmanBitBuffer* input) {
    THuffmanNode* pItemLink = nullptr;
    THuffmanNode* pItem;
    std::uint32_t item_link_index = 0;
    std::uint32_t bit_count = 0;
    bool has_item_link_index = HuffmanPeek7Bits(input, item_link_index);

    if (has_item_link_index &&
        decode_lut_[item_link_index].version == version_) {
        if (decode_lut_[item_link_index].bit_count <= 7) {
            HuffmanSkipBits(input, decode_lut_[item_link_index].bit_count);
            return static_cast<int>(decode_lut_[item_link_index].symbol);
        }

        pItem = reinterpret_cast<THuffmanNode*>(
            static_cast<std::uintptr_t>(decode_lut_[item_link_index].symbol));
        HuffmanSkipBits(input, 7);
    } else {

        pItem = GetFirstNode(sorted_list_);
        if (pItem == nullptr)
            return static_cast<int>(kHuffmanEOFSymbol);
    }

    while (pItem->child1 != nullptr) {
        const std::uint32_t bit_value = HuffmanGetBit(input);

        pItem = (bit_value != 0) ? GetPrevNode(pItem->child1) : pItem->child1;
        if (pItem == nullptr)
            return static_cast<int>(kHuffmanEOFSymbol);

        bit_count++;
        if (bit_count == 7) {
            pItemLink = pItem;
        }
    }

    (void)pItemLink;

    if (has_item_link_index &&
        decode_lut_[item_link_index].version != version_) {
        if (bit_count > 7) {
#if INTPTR_MAX == INT32_MAX
            decode_lut_[item_link_index].version = version_;
            decode_lut_[item_link_index].bit_count = bit_count;
            decode_lut_[item_link_index].symbol =
                static_cast<std::uint32_t>(
                    reinterpret_cast<std::uintptr_t>(pItemLink));
#endif
        } else {
            const std::uint32_t mask =
                (bit_count != 0)
                    ? (0xFFFFFFFFu >> (32 - bit_count))
                    : 0;
            for (std::uint32_t idx = item_link_index & mask;
                 idx < static_cast<std::uint32_t>(kHuffmanDecodeLUTSize);
                 idx += (1u << bit_count)) {
                decode_lut_[idx].version = version_;
                decode_lut_[idx].bit_count = bit_count;
                decode_lut_[idx].symbol = pItem->symbol;
            }
        }
    }

    return static_cast<int>(pItem->symbol);
}

void THuffmanTree::SplitNode(int new_symbol) {
    if (next_free_index_ + 2 > kHuffmanNodeCount)
        return;

    THuffmanNode* pLastItem = GetLastNode(sorted_list_);
    if (pLastItem == nullptr)
        return;

    const std::uint32_t old_symbol = pLastItem->symbol;

    THuffmanNode* pChildHi = AllocNode(1);
    if (pChildHi == nullptr)
        return;
    pChildHi->symbol = old_symbol;
    pChildHi->weight = pLastItem->weight;
    pChildHi->child0 = pLastItem;

    symbol_table_[old_symbol] = pChildHi;

    THuffmanNode* pChildLo = AllocNode(1);
    if (pChildLo == nullptr)
        return;
    pChildLo->symbol = static_cast<std::uint32_t>(new_symbol);
    pChildLo->weight = 0;
    pChildLo->child0 = pLastItem;

    pLastItem->symbol = kHuffmanEscapeSymbol;
    pLastItem->child1 = pChildLo;

    symbol_table_[new_symbol] = pChildLo;
}

void THuffmanTree::IncrementFreq(THuffmanNode* node) {
    if (node == nullptr)
        return;

    for (THuffmanNode* pItem = node; pItem != nullptr;
         pItem = pItem->child0) {
        pItem->weight++;

        THuffmanNode* pHigherItem =
            FindHigherOrEqualItem(sorted_list_, GetPrevNode(pItem), pItem->weight);
        THuffmanNode* pChildHi =
            (pHigherItem != nullptr) ? GetNextNode(pHigherItem) : nullptr;

        if (pChildHi != nullptr && pChildHi != pItem) {

            THuffmanNode* pParent = pItem->child0;
            THuffmanNode* pChildLo = (pChildHi->child0 != nullptr)
                                         ? pChildHi->child0->child1
                                         : nullptr;

            RemoveFromList(pChildHi);
            LinkTwoItems(sorted_list_, pItem, pChildHi);
            RemoveFromList(pItem);
            LinkTwoItems(sorted_list_, pHigherItem, pItem);

            if (pParent != nullptr && pParent->child1 == pItem)
                pParent->child1 = pChildHi;
            if (pChildLo != nullptr &&
                pChildLo == pChildHi &&
                pChildHi->child0 != nullptr) {
                pChildHi->child0->child1 = pItem;
            }

            pItem->child0 = pChildHi->child0;
            pChildHi->child0 = pParent;

            version_++;
        }
    }
}

std::uint32_t THuffmanTree::Decompress(std::uint8_t* output,
                                       std::uint32_t output_size,
                                       THuffmanBitBuffer* input) {
    if (output_size == 0)
        return 0;

    const std::uint32_t data_type = HuffmanGet8Bits(input);
    const bool is_sparse = (data_type == 0);

    BuildTree(static_cast<std::uint8_t>(data_type));

    std::uint8_t* write_ptr = output;
    std::uint8_t* write_end = output + output_size;

    while (true) {
        const int symbol = DecodeSymbol(input);
        if (symbol == kHuffmanEOFSymbol)
            break;

        if (symbol == kHuffmanEscapeSymbol) {

            const std::uint32_t raw_byte = HuffmanGet8Bits(input);

            SplitNode(static_cast<int>(raw_byte));

            if (!is_sparse)
                IncrementFreq(symbol_table_[raw_byte]);
        }

        if (write_ptr >= write_end)
            break;
        *write_ptr++ = static_cast<std::uint8_t>(symbol);

        if (is_sparse && symbol != kHuffmanEscapeSymbol &&
            symbol != kHuffmanEOFSymbol) {
            IncrementFreq(symbol_table_[symbol]);
        }
    }

    return static_cast<std::uint32_t>(write_ptr - output);
}

std::uint32_t THuffmanTree::Compress(THuffmanOutputBuffer* output,
                                     const std::uint8_t* input,
                                     std::uint32_t input_size,
                                     std::uint8_t compression_type) {

    BuildTree(compression_type);
    const bool is_sparse = ((compression_type & 0x0F) == 0);

    output->OutputBits(compression_type & 0x0F, 8);

    const std::uint8_t* read_ptr = input;
    const std::uint8_t* read_end = input + input_size;

    while (read_ptr < read_end) {
        const std::uint8_t input_byte = *read_ptr++;

        if (symbol_table_[input_byte] == nullptr) {

            EncodeSymbol(output, kHuffmanEscapeSymbol);
            output->OutputBits(input_byte, 8);

            SplitNode(input_byte);
            IncrementFreq(symbol_table_[input_byte]);
        } else {

            EncodeSymbol(output, input_byte);
        }

        if (is_sparse) {
            IncrementFreq(symbol_table_[input_byte]);
        }
    }

    EncodeSymbol(output, kHuffmanEOFSymbol);
    output->FlushBits();

    return static_cast<std::uint32_t>(
        output->write_ptr - output->base);
}

