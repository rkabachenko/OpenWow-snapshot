inline std::uint32_t HuffmanGetBit(THuffmanBitBuffer* buf) {
    if (buf->bits_left == 0) {
        buf->bit_cache = *buf->read_ptr++;
        buf->bits_left = 16;
    }
    const std::uint32_t bit = buf->bit_cache & 1;
    buf->bit_cache >>= 1;
    buf->bits_left--;
    return bit;
}

inline bool HuffmanPeek7Bits(THuffmanBitBuffer* buf, std::uint32_t& value) {
    while (buf->bits_left < 7) {
        buf->bit_cache |= static_cast<std::uint32_t>(*buf->read_ptr++)
                          << buf->bits_left;
        buf->bits_left += 16;
    }
    value = buf->bit_cache & 0x7F;
    return true;
}

inline void HuffmanSkipBits(THuffmanBitBuffer* buf, std::uint32_t count) {
    while (buf->bits_left < count) {
        buf->bit_cache |= static_cast<std::uint32_t>(*buf->read_ptr++)
                          << buf->bits_left;
        buf->bits_left += 16;
    }
    buf->bit_cache >>= count;
    buf->bits_left -= count;
}

inline std::uint32_t HuffmanGet8Bits(THuffmanBitBuffer* buf) {
    while (buf->bits_left < 8) {
        buf->bit_cache |= static_cast<std::uint32_t>(*buf->read_ptr++)
                          << buf->bits_left;
        buf->bits_left += 16;
    }
    const std::uint32_t value = buf->bit_cache & 0xFF;
    buf->bit_cache >>= 8;
    buf->bits_left -= 8;
    return value;
}

inline static bool IsSentinelOrNull(std::uintptr_t link_next) {
    return (link_next & kStormIntrusiveSentinelBit<std::uintptr_t>) != 0
           || link_next == 0;
}

inline static THuffmanNode* TokenToNode(std::uintptr_t token) {
    if (token == 0 || (token & kStormIntrusiveSentinelBit<std::uintptr_t>) != 0)
        return nullptr;
    return reinterpret_cast<THuffmanNode*>(token);
}

inline static StormIntrusiveLinkWords<std::uintptr_t>*
GetListSentinel(StormIntrusiveListRootWords<std::uintptr_t>& list) {
    return reinterpret_cast<StormIntrusiveLinkWords<std::uintptr_t>*>(
        &list.tail_link);
}

inline static THuffmanNode* GetFirstNode(
    const StormIntrusiveListRootWords<std::uintptr_t>& list) {
    return TokenToNode(list.head_node);
}

inline static THuffmanNode* GetLastNode(
    StormIntrusiveListRootWords<std::uintptr_t>& list) {
    auto* sentinel = GetListSentinel(list);
    return reinterpret_cast<THuffmanNode*>(sentinel->previous_link);
}

inline static THuffmanNode* GetNextNode(THuffmanNode* node) {
    return TokenToNode(node->link_next);
}

inline static THuffmanNode* GetPrevNode(THuffmanNode* node) {
    if (node->link_prev == 0)
        return nullptr;
    return reinterpret_cast<THuffmanNode*>(node->link_prev);
}

static void LinkTwoItems(StormIntrusiveListRootWords<std::uintptr_t>& list,
                         THuffmanNode* node1,
                         THuffmanNode* node2) {
    auto* sentinel = GetListSentinel(list);
    node2->link_prev = reinterpret_cast<std::uintptr_t>(&node1->link_prev);
    node2->link_next = node1->link_next;

    if (!IsSentinelOrNull(node1->link_next)) {
        auto* next_node = reinterpret_cast<THuffmanNode*>(node1->link_next);
        next_node->link_prev =
            reinterpret_cast<std::uintptr_t>(&node2->link_prev);
    } else {

        sentinel->previous_link =
            reinterpret_cast<std::uintptr_t>(&node2->link_prev);
    }
    node1->link_next = reinterpret_cast<std::uintptr_t>(node2);
}

inline static void RemoveFromList(THuffmanNode* node) {
    if (node->link_prev == 0)
        return;
    UnlinkStormIntrusiveNativeLink<std::uintptr_t>(
        reinterpret_cast<std::uintptr_t>(&node->link_prev));
}

static THuffmanNode* FindHigherOrEqualItem(
    StormIntrusiveListRootWords<std::uintptr_t>& list,
    THuffmanNode* start,
    std::uint32_t target_weight) {
    auto* sentinel = GetListSentinel(list);
    while (start != nullptr &&
           reinterpret_cast<std::uintptr_t>(start) !=
               reinterpret_cast<std::uintptr_t>(sentinel)) {
        if (start->weight >= target_weight)
            return start;
        start = GetPrevNode(start);
    }
    return nullptr;
}

static std::uint32_t FixupItemPosByWeight(
    StormIntrusiveListRootWords<std::uintptr_t>& list,
    THuffmanNode* pNewItem,
    std::uint32_t MaxWeight) {
    if (pNewItem->weight < MaxWeight) {
        THuffmanNode* pHigherOrEqual =
            FindHigherOrEqualItem(list, GetLastNode(list), pNewItem->weight);

        THuffmanNode* pAnchor = (pHigherOrEqual != nullptr)
                                    ? pHigherOrEqual
                                    : GetFirstNode(list);
        if (pAnchor != GetPrevNode(pNewItem)) {
            RemoveFromList(pNewItem);
            LinkTwoItems(list, pAnchor, pNewItem);
        }
        return MaxWeight;
    }
    return pNewItem->weight;
}

