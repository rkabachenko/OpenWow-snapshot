static inline int big2ByteType(const void* enc, const char* ptr) {
    auto hi = static_cast<unsigned char>(ptr[0]);
    auto lo = static_cast<unsigned char>(ptr[1]);
    if (hi != 0)
        return big2_charType(hi, lo);
    return static_cast<const unsigned char*>(enc)[kEncodingTypeTableOffset + lo];
}

static inline bool isNmstrt(unsigned char hi, unsigned char lo) {
    unsigned page = kNmstrtPages[hi];
    return ((1u << (lo & 0x1F)) &
            kNameBitmap[8 * page + (lo >> 5)]) != 0;
}

static inline bool isName(unsigned char hi, unsigned char lo) {
    unsigned page = kNamePages[hi];
    return ((1u << (lo & 0x1F)) &
            kNameBitmap[8 * page + (lo >> 5)]) != 0;
}

int big2_charType(unsigned char hi, unsigned char lo) {
    switch (static_cast<signed char>(hi)) {
    case -40:
    case -39:
    case -38:
    case -37:
        return bt::kLead4;
    case -36:
    case -35:
    case -34:
    case -33:
        return bt::kTrail;
    case -1:
        if (lo < 0xFE)
            return bt::kNonAscii;
        return bt::kNonXml;
    default:
        return bt::kNonAscii;
    }
}

int big2_scanHexCharRef(const void* enc, const char* ptr,
                        const char* end, const char** nextTokPtr) {
    if (ptr == end)
        return xml_tok::kPartial;

    int type = big2ByteType(enc, ptr);

    if (static_cast<unsigned>(type - bt::kHex) > 1) {
        *nextTokPtr = ptr;
        return xml_tok::kInvalid;
    }

    ptr += 2;
    if (ptr == end)
        return xml_tok::kPartial;

    for (;;) {
        type = big2ByteType(enc, ptr);
        if (type == bt::kSemi) {
            *nextTokPtr = ptr + 2;
            return xml_tok::kCharRef;
        }
        if (static_cast<unsigned>(type - bt::kHex) > 1) {
            *nextTokPtr = ptr;
            return xml_tok::kInvalid;
        }
        ptr += 2;
        if (ptr == end)
            return xml_tok::kPartial;
    }
}

int big2_scanCharRef(const void* enc, const char* ptr,
                     const char* end, const char** nextTokPtr) {
    if (ptr == end)
        return xml_tok::kPartial;

    if (static_cast<unsigned char>(ptr[0]) == 0 &&
        static_cast<unsigned char>(ptr[1]) == 0x78) {
        return big2_scanHexCharRef(enc, ptr + 2, end, nextTokPtr);
    }

    int type = big2ByteType(enc, ptr);

    if (type != bt::kDigit) {
        *nextTokPtr = ptr;
        return xml_tok::kInvalid;
    }

    ptr += 2;
    if (ptr == end)
        return xml_tok::kPartial;

    for (;;) {
        type = big2ByteType(enc, ptr);
        if (type == bt::kSemi) {
            *nextTokPtr = ptr + 2;
            return xml_tok::kCharRef;
        }
        if (type != bt::kDigit) {
            *nextTokPtr = ptr;
            return xml_tok::kInvalid;
        }
        ptr += 2;
        if (ptr == end)
            return xml_tok::kPartial;
    }
}

int big2_scanRef(const void* enc, const char* ptr,
                 const char* end, const char** nextTokPtr) {
    if (ptr == end)
        return xml_tok::kPartial;

    auto hi = static_cast<unsigned char>(ptr[0]);
    int type;
    if (hi != 0)
        type = big2_charType(hi, static_cast<unsigned char>(ptr[1]));
    else
        type = static_cast<const unsigned char*>(
            enc)[kEncodingTypeTableOffset + static_cast<unsigned char>(ptr[1])];

    switch (type) {
    case bt::kLead2:
        if (end - ptr >= 2)
            break;
        return xml_tok::kPartialChar;
    case bt::kLead3:
        if (end - ptr >= 3)
            break;
        return xml_tok::kPartialChar;
    case bt::kLead4:
        if (end - ptr >= 4)
            break;
        return xml_tok::kPartialChar;
    case bt::kNum:
        return big2_scanCharRef(enc, ptr + 2, end, nextTokPtr);
    case bt::kNmstrt:
    case bt::kHex:
        goto scan_name;
    case bt::kNonAscii:
        if (!isNmstrt(hi, static_cast<unsigned char>(ptr[1])))
            break;
        goto scan_name;
    default:
        break;
    }

    *nextTokPtr = ptr;
    return xml_tok::kInvalid;

scan_name:
    ptr += 2;
    if (ptr == end)
        return xml_tok::kPartial;

    for (;;) {
        hi = static_cast<unsigned char>(ptr[0]);
        if (hi != 0)
            type = big2_charType(hi, static_cast<unsigned char>(ptr[1]));
        else
            type = static_cast<const unsigned char*>(
                enc)[kEncodingTypeTableOffset +
                     static_cast<unsigned char>(ptr[1])];

        switch (type) {
        case bt::kLead2:
            if (end - ptr < 2) return xml_tok::kPartialChar;
            break;
        case bt::kLead3:
            if (end - ptr < 3) return xml_tok::kPartialChar;
            break;
        case bt::kLead4:
            if (end - ptr < 4) return xml_tok::kPartialChar;
            break;
        case bt::kSemi:
            *nextTokPtr = ptr + 2;
            return xml_tok::kEntityRef;
        case bt::kNmstrt:
        case bt::kHex:
        case bt::kDigit:
        case bt::kName:
        case bt::kMinus:
            ptr += 2;
            if (ptr == end) return xml_tok::kPartial;
            continue;
        case bt::kNonAscii:
            if (!isName(hi, static_cast<unsigned char>(ptr[1])))
                goto not_name;
            ptr += 2;
            if (ptr == end) return xml_tok::kPartial;
            continue;
        default:
            goto not_name;
        }

        goto not_name;
    }

not_name:
    *nextTokPtr = ptr;
    return xml_tok::kInvalid;
}

int big2_attributeValueTok(const void* enc, const char* ptr,
                           const char* end, const char** nextTokPtr) {
    const char* start = ptr;

    if (ptr == end)
        return xml_tok::kNone;

    for (;;) {
        int type = big2ByteType(enc, ptr);

        switch (type) {
        case bt::kLt:
            *nextTokPtr = ptr;
            return xml_tok::kInvalid;

        case bt::kAmp:
            if (ptr != start) {
                *nextTokPtr = ptr;
                return xml_tok::kDataChars;
            }
            return big2_scanRef(enc, ptr + 2, end, nextTokPtr);

        case bt::kLead3:
            ptr += 3;
            if (ptr == end) {
                *nextTokPtr = ptr;
                return xml_tok::kDataChars;
            }
            continue;

        case bt::kLead4:
            ptr += 4;
            if (ptr == end) {
                *nextTokPtr = ptr;
                return xml_tok::kDataChars;
            }
            continue;

        case bt::kCr:
            if (ptr != start) {
                *nextTokPtr = ptr;
                return xml_tok::kDataChars;
            }
            ptr += 2;
            if (ptr == end)
                return xml_tok::kTrailingCr;
            if (big2ByteType(enc, ptr) == bt::kLf)
                ptr += 2;
            *nextTokPtr = ptr;
            return xml_tok::kDataNewline;

        case bt::kLf:
            if (ptr != start) {
                *nextTokPtr = ptr;
                return xml_tok::kDataChars;
            }
            *nextTokPtr = ptr + 2;
            return xml_tok::kDataNewline;

        case bt::kS:
            if (ptr == start) {
                *nextTokPtr = ptr + 2;
                return xml_tok::kAttributeValueS;
            }
            *nextTokPtr = ptr;
            return xml_tok::kDataChars;

        default:
            ptr += 2;
            if (ptr == end) {
                *nextTokPtr = ptr;
                return xml_tok::kDataChars;
            }
            continue;
        }
    }
}

