const std::uint8_t kScanDllSignatureExponent[4] = {0x01, 0x00, 0x01, 0x00};

bool CheckExecutableSignatureFromBuffer(const void* data, std::size_t size,
                                        const void* modulus,
                                        const void* exponent) {
    if (!data || size == 0) {
        return false;
    }

    void* ctx = nullptr;
    openwow::core::SSignature_Create(&ctx, 256, 4);
    openwow::core::SSignature_Update(ctx, data, size);
    return openwow::core::SSignature_Verify(ctx, modulus, exponent);
}

bool CheckExecutableSignatureFromBuffer(const void* data, std::size_t size) {
    return CheckExecutableSignatureFromBuffer(data, size,
                                              kScanDllSignatureModulus,
                                              kScanDllSignatureExponent);
}

bool CheckExecutableSignature(const char* path) {
    using namespace openwow::vfs;

    if (!path) {
        return false;
    }

    const int handle = OS_FileOpen(path, 0x80000000, 1, 3, 128);
    if (handle == 0) {
        return false;
    }

    bool result = false;

    const auto file_size =
        static_cast<std::size_t>(IOUnitContainer_GetFileSizeByHandle(handle));
    if (file_size != 0) {
        std::vector<std::uint8_t> buffer(file_size);
        std::uint32_t bytes_read = 0;
        IOUnitContainer_ReadFileHandle_Wrapper(
            handle, buffer.data(), static_cast<std::uint32_t>(file_size),
            &bytes_read);

        if (!buffer.empty()) {
            result = CheckExecutableSignatureFromBuffer(
                buffer.data(), bytes_read);
        }
    }

    IOUnitContainer_CloseFileHandle(handle);
    return result;
}

