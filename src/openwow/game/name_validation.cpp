void BindNameValidationDbcLoader(const openwow::data::dbc::DbcLoader *dbc,
                                 std::uint32_t locale_mask,
                                 std::uint32_t default_locale_mask) {
  std::lock_guard<std::mutex> lock(g_name_filter_mutex);
  if (g_name_filters_initialized && g_bound_name_filter_dbc == dbc &&
      g_bound_name_filter_locale_mask == locale_mask &&
      g_bound_name_filter_default_locale_mask == default_locale_mask) {
    return;
  }

  g_name_filters_initialized = true;
  g_bound_name_filter_dbc = dbc;
  g_bound_name_filter_locale_mask = locale_mask;
  g_bound_name_filter_default_locale_mask = default_locale_mask;
  g_validation_default_locale_mask = default_locale_mask;
  if (dbc == nullptr) {
    g_name_profanity_filters = {};
    g_chat_profanity_filters = {};
    g_name_reserved_filters = {};
    g_name_spam_filters.clear();
    return;
  }

  g_name_profanity_filters =
      BuildLocalizedNameFilters(dbc->names_profanity(), "NamesProfanity", locale_mask);
  g_chat_profanity_filters = BuildChatProfanityFilters(dbc, locale_mask);
  g_name_reserved_filters =
      BuildLocalizedNameFilters(dbc->names_reserved(), "NamesReserved", locale_mask);
  g_name_spam_filters = BuildNameSpamFilters(dbc);
}

std::uint32_t GetValidationDefaultLocaleMask() {
  std::lock_guard<std::mutex> lock(g_name_filter_mutex);
  return g_validation_default_locale_mask;
}

bool MatchesChatProfanity(const std::string &text, std::uint32_t locale_index) {
  std::lock_guard<std::mutex> lock(g_name_filter_mutex);
  if (locale_index >= kNameFilterLocaleCount) {
    return false;
  }
  return MatchesNameFilterList(text, g_chat_profanity_filters[locale_index]);
}

NameValidationResult ValidateName(std::uint32_t locale_index, const char16_t *allowed_extra,
                                  const std::string &name, std::uint32_t &out_length,
                                  int &out_locale, bool check_profanity, bool check_reserved,
                                  bool check_spam, bool skip_structure, bool check_force_english,
                                  int explicit_locale) {

  if (name.empty())
    return NameValidationResult::kNoName;

  const auto decoded_name = Utf8ToUtf16(name);
  if (!decoded_name.has_value() || decoded_name->empty())
    return NameValidationResult::kFailure;
  const auto &wname = *decoded_name;

  if (locale_index > 8)
    return NameValidationResult::kFailure;

  std::uint32_t locale_mask = 0;
  bool restrict_locales = false;
  std::uint32_t default_locale_mask = 0;
  {
    std::lock_guard<std::mutex> lock(g_name_filter_mutex);
    default_locale_mask = g_validation_default_locale_mask;
  }
  if (explicit_locale == -1) {
    if (check_force_english && IsForceEnglishNamesEnabled()) {
      locale_mask = 1u << static_cast<int>(NameLocale::kAsciiAlpha);
      restrict_locales = true;
    } else if (default_locale_mask != 0) {
      locale_mask = default_locale_mask;
      restrict_locales = true;
    }
  } else if (explicit_locale != 0) {
    locale_mask = static_cast<std::uint32_t>(explicit_locale);
    restrict_locales = true;
  }

  out_locale = -1;
  out_length = 0;
  int apostrophe_pos = -1;
  int space_pos = -1;

  for (std::size_t i = 0; i < wname.size(); ++i) {
    char16_t ch = wname[i];
    ++out_length;

    if (out_locale == -1) {
      for (int loc = 0; loc < 5; ++loc) {
        if (restrict_locales && ((1u << loc) & locale_mask) == 0)
          continue;
        if (BelongsToLocale(ch, loc)) {
          out_locale = loc;
          break;
        }
      }
    }

    if (out_locale >= 0 && BelongsToLocale(ch, out_locale)) {

      if (!skip_structure && out_length >= 3) {
        char16_t c1 = ToLower(wname[out_length - 1]);
        char16_t c2 = ToLower(wname[out_length - 2]);
        char16_t c3 = ToLower(wname[out_length - 3]);
        if (c1 == c2 && c1 == c3)
          return NameValidationResult::kTripleLetterDisallowed;
      }

      if (out_locale == 2) {
        char16_t c_lower = ToLower(wname[out_length - 1]);

        if (out_length == 1 && (c_lower == 0x044A || c_lower == 0x044C))
          return NameValidationResult::kLeadingSoftHardSign;

        if (c_lower == 0x044A) {
          char16_t next_ch = (i + 1 < wname.size()) ? wname[i + 1] : u'\0';
          if (next_ch == u'\0' || next_ch == u' ')
            return NameValidationResult::kLeadingSoftHardSign;
        }

        if (out_length >= 2 && (c_lower == 0x044A || c_lower == 0x044C)) {
          char16_t prev = ToLower(wname[out_length - 2]);
          if (prev == 0x044A || prev == 0x044C)
            return NameValidationResult::kConsecutiveSoftHardSign;
        }
      }
      continue;
    }

    if (allowed_extra) {
      bool found = false;
      for (const char16_t *p = allowed_extra; *p; ++p) {
        if (*p == ch) {
          found = true;
          break;
        }
      }
      if (found) {

        if (!skip_structure) {
          if (ch == u'\'') {
            if (out_length == 1)
              return NameValidationResult::kLeadingApostrophe;
            if (apostrophe_pos >= 0)
              return NameValidationResult::kTripleSameChar;
            apostrophe_pos = static_cast<int>(out_length) - 1;
          } else if (ch == u' ') {
            if (out_length == 1)
              return NameValidationResult::kLeadingSpace;
            if (out_length > 1 && space_pos == static_cast<int>(out_length) - 2)
              return NameValidationResult::kConsecutiveSpaces;
            space_pos = static_cast<int>(out_length) - 1;
          }
        }
        continue;
      }
    }

    return NameValidationResult::kInvalidCharacter;
  }

  if (!skip_structure && out_length > 0) {
    if (out_length < 2)
      return (out_length != 0) ? NameValidationResult::kTooShortForLocale
                               : NameValidationResult::kNoName;
    auto last_idx = static_cast<int>(out_length) - 1;
    if (apostrophe_pos == last_idx)
      return NameValidationResult::kLeadingApostrophe;
    if (space_pos == last_idx)
      return NameValidationResult::kLeadingSpace;
  }

  {
    std::lock_guard<std::mutex> lock(g_name_filter_mutex);
    const auto locale_slot = static_cast<std::size_t>(locale_index);
    if (check_profanity && MatchesNameFilterList(name, g_name_profanity_filters[locale_slot])) {
      return NameValidationResult::kProfanity;
    }
    if (check_reserved && MatchesNameFilterList(name, g_name_reserved_filters[locale_slot])) {
      return NameValidationResult::kReserved;
    }
    if (check_spam && MatchesNameFilterList(name, g_name_spam_filters)) {
      return NameValidationResult::kProfanity;
    }
  }

  return NameValidationResult::kOk;
}

static NameValidationResult ValidateNameWithLocaleLengthCap(const std::uint32_t locale_index,
                                                            const std::string &name,
                                                            const bool honor_force_english,
                                                            const std::uint32_t extra_allowance) {
  std::uint32_t length = 0;
  int locale = -1;
  const auto result = ValidateName(locale_index, nullptr, name, length, locale, true, true, true,
                                   false, honor_force_english, -1);
  if (result != NameValidationResult::kOk) {
    return result;
  }

  std::uint32_t max_length = 12 + extra_allowance;
  if (locale == static_cast<int>(NameLocale::kKorean)) {
    max_length = 8 + extra_allowance;
  } else if (locale == static_cast<int>(NameLocale::kCjk)) {
    max_length = 6 + extra_allowance;
  }

  if (length > max_length) {
    return NameValidationResult::kLengthExceeded;
  }
  return NameValidationResult::kOk;
}

NameValidationResult ValidateGlueCharacterName(const std::string &name) {
  return ValidateNameWithLocaleLengthCap(Localization::Get().GetLocaleIndex(), name, true, 0);
}

std::uint8_t ValidateGlueCharacterNameResultCode(const std::string &name) {
  constexpr std::uint8_t kCharacterNameSuccess = 87;
  return static_cast<std::uint8_t>(kCharacterNameSuccess +
                                   static_cast<int>(ValidateGlueCharacterName(name)));
}

NameValidationResult ValidatePetName(const std::string &name, std::uint32_t max_extra) {
  const auto locale_index =
      static_cast<std::uint32_t>(Localization::Get().GetLocaleIndex());

  std::uint32_t length = 0;
  int locale = -1;

  const auto result = ValidateName(locale_index, nullptr, name, length, locale,
                                   true,
                                   true,
                                   true,
                                   false,
                                   true, -1);
  if (result != NameValidationResult::kOk)
    return result;

  std::uint32_t base = 12;
  if (locale == static_cast<int>(NameLocale::kKorean) ||
      locale == static_cast<int>(NameLocale::kCjk))
    base = 8;

  if (length > max_extra + base)
    return NameValidationResult::kLengthExceeded;

  return NameValidationResult::kOk;
}

NameValidationResult ValidatePetitionName(const std::uint32_t locale_index,
                                          const std::string &name) {
  static const char16_t kAllowed[] = {u' ', 0};

  std::uint32_t length = 0;
  int locale = -1;
  auto result = ValidateName(locale_index, kAllowed, name, length, locale, true, true, false, false,
                             false, -1);
  if (result != NameValidationResult::kOk)
    return result;
  if (length > 24)
    return NameValidationResult::kLengthExceeded;
  return NameValidationResult::kOk;
}

NameValidationResult ValidateGuildBankTabName(const std::string &name) {
  static const char16_t kAllowed[] = {u' ', u'1', u'2', u'3', u'4', u'5',
                                      u'6', u'7', u'8', u'9', u'0', 0};
  std::uint32_t length = 0;
  int locale = -1;
  auto result = ValidateName(0, kAllowed, name, length, locale, true, true, false, true, false, -1);
  if (result != NameValidationResult::kOk)
    return result;
  if (length > 16)
    return NameValidationResult::kLengthExceeded;
  return NameValidationResult::kOk;
}

bool CapitalizeName(const std::string &input, std::string &output) {
  output.clear();
  if (input.empty())
    return true;

  const auto decoded_name = Utf8ToUtf16(input);
  if (!decoded_name.has_value() || decoded_name->empty())
    return true;
  auto wname = *decoded_name;

  wname[0] = RetailNameToUpper(wname[0]);

  for (std::size_t i = 1; i < wname.size(); ++i) {
    wname[i] = ToLower(wname[i]);
  }

  output = Utf16ToUtf8(wname);
  return true;
}

