std::optional<openwow::foundation::text::RetailRegex>
CompileNameFilter(const std::string_view pattern, const char *table_name, const std::uint32_t id) {
  auto compiled =
      openwow::foundation::text::RetailRegex::Compile(std::string(pattern));
  if (!compiled.has_value()) {
    diagnostics::Log(diagnostics::LogLevel::kWarn, std::string(table_name) + ": skipping invalid expression \"" +
                                         std::string(pattern) + "\" (record ID " +
                                         std::to_string(id) + ")");
  }
  return compiled;
}

template <typename EntryStore>
LocalizedNameExpressionTable BuildLocalizedNameFilters(const EntryStore &store,
                                                       const char *table_name,
                                                       const std::uint32_t locale_mask) {
  LocalizedNameExpressionTable compiled;
  for (std::size_t locale = 0; locale < compiled.size(); ++locale) {
    if (locale_mask != 0 && (locale_mask & (1u << locale)) == 0) {
      continue;
    }

    auto &locale_filters = compiled[locale];
    locale_filters.reserve(store.entries().size());
    for (const auto &entry : store.entries()) {
      if (entry.language != 0xFFFFFFFFu && entry.language != locale) {
        continue;
      }

      if (auto regex = CompileNameFilter(entry.pattern, table_name, entry.id); regex.has_value()) {
        locale_filters.push_back(std::move(*regex));
      }
    }
  }
  return compiled;
}

LocalizedNameExpressionTable BuildChatProfanityFilters(
    const openwow::data::dbc::DbcLoader *dbc, const std::uint32_t locale_mask) {
  LocalizedNameExpressionTable compiled;
  if (dbc == nullptr) {
    return compiled;
  }

  const auto &store = dbc->chat_profanity();
  for (std::size_t locale = 0; locale < compiled.size(); ++locale) {
    if (locale_mask != 0 && (locale_mask & (1u << locale)) == 0) {
      continue;
    }

    auto &locale_filters = compiled[locale];
    locale_filters.reserve(store.entries().size());
    for (const auto &entry : store.entries()) {
      if (entry.language != 0xFFFFFFFFu && entry.language != locale) {
        continue;
      }

      if (auto regex = CompileNameFilter(entry.text, "ChatProfanity", entry.id); regex.has_value()) {
        locale_filters.push_back(std::move(*regex));
      }
    }
  }
  return compiled;
}

CompiledNameExpressionList BuildNameSpamFilters(const openwow::data::dbc::DbcLoader *dbc) {
  CompiledNameExpressionList compiled;
  if (dbc == nullptr) {
    return compiled;
  }

  compiled.reserve(dbc->spam_messages().entries().size());
  for (const auto &entry : dbc->spam_messages().entries()) {
    if (auto regex = CompileNameFilter(entry.pattern, "SpamMessages", entry.id);
        regex.has_value()) {
      compiled.push_back(std::move(*regex));
    }
  }
  return compiled;
}

bool MatchesNameFilterList(const std::string &name, const CompiledNameExpressionList &filters) {
  for (const auto &filter : filters) {
    if (filter.Matches(name)) {
      return true;
    }
  }
  return false;
}

