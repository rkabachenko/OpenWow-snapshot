bool IsLatinChar(char16_t c) {
  if (c >= u'A' && c <= u'Z')
    return true;
  if (c >= u'a' && c <= u'z')
    return true;
  if (c >= 0x00C0 && c <= 0x00DD && c != 0x00D7)
    return true;
  if (c == 0x00DF)
    return true;
  if (c >= 0x00E0 && c <= 0x00FF && c != 0x00F7 && c != 0x00FE)
    return true;
  return false;
}

bool IsRussianChar(char16_t c) {
  if (c >= 0x0410 && c <= 0x044F)
    return true;
  if (c == 0x0401 || c == 0x0451)
    return true;
  return false;
}

bool IsAsciiAlphaChar(char16_t c) {
  return (c >= u'A' && c <= u'Z') || (c >= u'a' && c <= u'z');
}

bool IsKoreanChar(char16_t c) {
  if (c < kKoreanNameBase || c > kKoreanNameLimit) {
    return false;
  }

  const auto index = static_cast<std::uint32_t>(c - kKoreanNameBase);
  return (kKoreanNameBitmap[index / 8] & (1u << (index % 8))) != 0;
}

bool BelongsToLocale(char16_t c, int locale) {
  switch (locale) {
  case 0:
    return IsLatinChar(c);
  case 1:
    return IsAsciiAlphaChar(c);
  case 2:
    return IsRussianChar(c);
  case 3:
    return IsKoreanChar(c);
  case 4:
    return (c >= 0x4E00 && c <= 0x9FFF) || (c >= 0x3400 && c <= 0x4DFF) ||
           (c >= 0xF900 && c <= 0xFAFF);
  default:
    return false;
  }
}

